from datetime import datetime
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field, field_validator


class ChatRequest(BaseModel):
    """Payload for conversational interaction with The Lenny Growth Assistant."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question or prompt for the assistant",
        examples=["What are the best frameworks for B2B user retention?"],
    )
    session_id: Optional[uuid.UUID] = Field(
        default=None,
        description="Optional UUID of an existing conversation session for multi-turn chat",
    )
    provider: Optional[str] = Field(
        default=None,
        description="Optional LLM provider override ('ollama' or 'anthropic')",
    )
    model: Optional[str] = Field(
        default=None,
        description="Optional model override for the selected provider",
    )
    agent_framework: Optional[str] = Field(
        default=None,
        description="Optional agent framework override ('pi_coding_agent' or 'anthropic_tool_agent')",
    )

    @field_validator("message")
    @classmethod
    def validate_non_empty_message(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("Chat message cannot be empty or pure whitespace.")
        return clean


class SourceCitation(BaseModel):
    """Structured citation referencing an ingested transcript chunk."""

    chunk_id: uuid.UUID = Field(..., description="Unique chunk UUID")
    transcript_id: uuid.UUID = Field(..., description="Unique parent transcript UUID")
    transcript_title: str = Field(..., description="Title of the source transcript")
    source_filename: str = Field(..., description="Disk filename of the source transcript")
    chunk_index: int = Field(..., description="Index of the chunk in the parent transcript")
    chunk_text: str = Field(..., description="Text content or excerpt of the retrieved chunk")
    score: float = Field(..., description="Relevance score calculated during retrieval")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Provenance metadata (e.g. guest, topic, synthetic flags)",
    )


class ChatResponse(BaseModel):
    """Structured response from the Grounded Growth Assistant."""

    session_id: uuid.UUID = Field(..., description="Active conversation session UUID")
    message: str = Field(..., description="Grounded response text generated by the assistant")
    role: str = Field(default="assistant", description="Message role")
    provider: str = Field(..., description="LLM provider utilized ('ollama' or 'anthropic')")
    model: str = Field(..., description="Model identifier utilized for generation")
    agent_framework: str = Field(
        default="anthropic_tool_agent",
        description="Active agent orchestration framework ('anthropic_tool_agent', 'pi_coding_agent', etc.)",
    )
    sources: List[SourceCitation] = Field(
        default_factory=list,
        description="Verified source citations grounding the response",
    )
    insufficient_evidence: bool = Field(
        default=False,
        description="Indicates whether the knowledge base lacked sufficient evidence to answer",
    )
    created_at: datetime = Field(
        default_factory=datetime.utcnow,
        description="Timestamp of response creation",
    )


class MessageItem(BaseModel):
    """Individual message item representation."""
    id: uuid.UUID = Field(..., description="Unique message UUID")
    role: str = Field(..., description="Speaker role ('user' or 'assistant')")
    content: str = Field(..., description="Message text content")
    created_at: datetime = Field(..., description="Message timestamp in UTC")


class SessionSummary(BaseModel):
    """Summary of a saved conversation session."""
    id: uuid.UUID = Field(..., description="Conversation session UUID")
    title: str = Field(..., description="Title or topic summary of the conversation")
    created_at: datetime = Field(..., description="Session creation timestamp in UTC")
    updated_at: datetime = Field(..., description="Session last updated timestamp in UTC")
    message_count: int = Field(default=0, description="Total number of messages in the session")
    last_message: Optional[str] = Field(default=None, description="Preview of the most recent message")


class SessionDetail(BaseModel):
    """Complete detail of a conversation session including full message history."""
    id: uuid.UUID = Field(..., description="Conversation session UUID")
    title: str = Field(..., description="Title or topic summary of the conversation")
    created_at: datetime = Field(..., description="Session creation timestamp in UTC")
    updated_at: datetime = Field(..., description="Session last updated timestamp in UTC")
    messages: List[MessageItem] = Field(default_factory=list, description="Ordered conversation messages")


class SessionRenameRequest(BaseModel):
    """Payload for renaming a conversation session."""
    title: str = Field(..., min_length=1, max_length=255, description="New title for the session")

    @field_validator("title")
    @classmethod
    def validate_title(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("Session title cannot be empty or pure whitespace.")
        return clean
